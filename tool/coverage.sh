#!/usr/bin/env bash
# Honest coverage: Flutter's lcov only lists files some test imports, which hides untested
# screens. This imports every file under lib/ first so untested code counts as 0%.
set -euo pipefail
cd "$(dirname "$0")/.."

helper=test/_all_files_coverage_test.dart
{
  echo "// GENERATED by tool/coverage.sh - not committed."
  echo "// ignore_for_file: unused_import, directives_ordering"
  find lib -name '*.dart' ! -path 'lib/l10n/generated/*' | sort | while read -r f; do
    echo "import 'package:shopsphere/${f#lib/}';"
  done
  echo "void main() {}"
} > "$helper"
trap 'rm -f "$helper"' EXIT

flutter test --coverage
python tool/coverage_summary.py
